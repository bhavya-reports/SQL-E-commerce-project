-- 9. Show every product that has been ordered (product name, category, quantity ordered)
SELECT 
    p.product_name,
    p.category,
    SUM(oi.quantity) AS quantity_ordered
FROM products AS p
INNER JOIN order_item AS oi
    ON p.product_id = oi.product_id
GROUP BY p.product_id, p.product_name, p.category;
  
-- 10. Show all customers and their orders, including customers who have never placed an order.
