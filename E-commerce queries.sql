-- 25. Find customers who have placed more than 3 orders.
SELECT c.customer_id, c.first_name, count(o.order_id) as orders_placed
FROM customers AS c
LEFT JOIN orders AS o
  ON c.customer_id=o.customer_id
GROUP BY c.customer_id
HAVING orders_placed>3
ORDER BY orders_placed DESC;

-- 26.Find the average amount spent per customer.
SELECT customer_id, first_name,
    AVG(order_total) AS avg_spent_per_order
FROM (
    SELECT
        c.customer_id,
        c.first_name,
        o.order_id,
        SUM(p.price * oi.quantity) AS order_total
    FROM customers AS c
    JOIN orders AS o
        ON c.customer_id = o.customer_id
    JOIN order_item AS oi
        ON o.order_id = oi.order_id
    JOIN products AS p
        ON oi.product_id = p.product_id
    GROUP BY c.customer_id, c.first_name, o.order_id
) AS customer_orders
GROUP BY customer_id, first_name;

