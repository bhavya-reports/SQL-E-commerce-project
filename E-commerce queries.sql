-- 38.Find the best-selling product in each category.
WITH product_sales AS (
    SELECT
        p.category,
        p.product_id,
        p.product_name,
        SUM(oi.quantity) AS total_sold
    FROM products AS p
    JOIN order_item AS oi
        ON p.product_id = oi.product_id
    GROUP BY p.category, p.product_id, p.product_name
),
ranked_products AS (
    SELECT
        category,
        product_name,
        total_sold,
        RANK() OVER (
            PARTITION BY category
            ORDER BY total_sold DESC
        ) AS product_rank
    FROM product_sales
)
SELECT
    category,
    product_name,
    total_sold
FROM ranked_products
WHERE product_rank = 1;

-- 39.Find the country with the highest average order value.
SELECT country, AVG(order_value) AS avg_order_value
FROM (
    SELECT
        c.country,
        o.order_id,
        SUM(p.price * oi.quantity) AS order_value
    FROM customers AS c
    JOIN orders AS o
        ON c.customer_id = o.customer_id
    JOIN order_item AS oi
        ON o.order_id = oi.order_id
    JOIN products AS p
        ON oi.product_id = p.product_id
	GROUP BY c.country,o.order_id
    ) AS country_order
    GROUP BY country
    ORDER BY avg_order_value DESC
    LIMIT 1;
  
-- 40.Find customers who have purchased products from at least 3 different categories.
SELECT
    c.customer_id,
    c.first_name,
    c.last_name,
    COUNT(DISTINCT p.category) AS categories_purchased
FROM customers AS c
JOIN orders AS o
    ON c.customer_id = o.customer_id
JOIN order_item AS oi
    ON o.order_id = oi.order_id
JOIN products AS p
    ON oi.product_id = p.product_id
GROUP BY c.customer_id, c.first_name, c.last_name
HAVING COUNT(DISTINCT p.category) >= 3;
