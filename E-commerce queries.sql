-- 18. Calculate average order value.
SELECT AVG(order_total) AS average_order_value
FROM(
   SELECT 
     order_item.order_id, sum(quantity*price) AS order_total
   FROM order_item
   INNER JOIN products
     ON order_item.product_id=products.product_id
   GROUP BY order_item.order_id
   ) AS order_total;
   
